// Maps detected boxes to icon names (in order: row 1 left-to-right, then row 2, ...)
// and writes public/icons.css with CSS classes plus a manifest JSON for JS use.
const fs = require('fs');
const path = require('path');

const IN = path.join(__dirname, '..', 'data', 'sprite-boxes.json');
const OUT_CSS = path.join(__dirname, '..', 'public', 'icons.css');
const OUT_JSON = path.join(__dirname, '..', 'public', 'icons-manifest.json');

const NAMES_BY_ROW = [
  // Row 1 — 11
  ['shield-check', 'lock', 'lock-2', 'lock-3', 'key', 'hat', 'hood', 'hook', 'magnifier', 'dragon', 'compass'],
  // Row 2 — 13
  ['shield-check-2', 'x-hex', 'warning', 'sq-empty', 'sq-check', 'check', 'x', 'lightning', 'rocket', 'sparkles', 'star', 'star-2', 'star-3'],
  // Row 3 — 13
  ['box', 'folder-open', 'folder-closed', 'document', 'terminal', 'scroll', 'clipboard', 'robot', 'windows', 'penguin', 'gear', 'globe', 'antenna'],
  // Row 4 — 5
  ['chat', 'satellite', 'floppy', 'disc', 'gamepad'],
  // Row 5 — 13
  ['eye', 'arrows-down', 'arrow-down', 'arrow-right', 'arrow-left', 'arrow-up', 'arrows-up', 'trash', 'edit', 'pencil', 'plus', 'minus', 'stopwatch'],
  // Row 6 — 14
  ['hourglass', 'alarm', 'hourglass-2', 'lightbulb', 'email-at', 'email-open', 'paper-plane', 'megaphone', 'bell', 'target', 'trophy', 'coins', 'credit-card', 'gift'],
  // Row 7 — 8
  ['party', 'fire', 'hundred', 'profile', 'group', 'laptop', 'network', 'building'],
];

const data = JSON.parse(fs.readFileSync(IN, 'utf8'));
const { sprite, boxes } = data;
const W = sprite.width, H = sprite.height;

// Group boxes by row index
const rows = {};
boxes.forEach((b) => { (rows[b.row] = rows[b.row] || []).push(b); });
const rowKeys = Object.keys(rows).map(Number).sort((a, b) => a - b);

const manifest = {};
const cssLines = [];
cssLines.push(`/* AUTO-GENERATED by tools/build-icon-css.js — do not edit */`);
cssLines.push(`.icon {`);
cssLines.push(`  display: inline-block; vertical-align: middle;`);
cssLines.push(`  width: 1.2em; height: 1.2em;`);
cssLines.push(`  background-image: url('/icons/sprite.png');`);
cssLines.push(`  background-repeat: no-repeat;`);
cssLines.push(`  background-size: ${(W / 100).toFixed(2)}em auto; /* fallback, overridden per icon */`);
cssLines.push(`}`);
cssLines.push(``);

let totalNamed = 0;
rowKeys.forEach((rk) => {
  const rowBoxes = rows[rk];
  const names = NAMES_BY_ROW[rk] || [];
  rowBoxes.forEach((b, ci) => {
    const name = names[ci] || `r${rk}-c${ci}`;
    // Add a small padding so glow isn't cut
    const pad = 4;
    const x = Math.max(0, b.x - pad);
    const y = Math.max(0, b.y - pad);
    const w = Math.min(W - x, b.w + pad * 2);
    const h = Math.min(H - y, b.h + pad * 2);
    manifest[name] = { x, y, w, h };
    totalNamed++;
    // Use scale: render at 1.2em tall keeping aspect; we set width via JS or .icon-XXX width.
    // CSS approach: each icon class sets background-position and bg-size such that the cell maps to 1em area.
    // Simpler: set bg-size = (W/h) em x (H/h) em, position = -(x/h)em -(y/h)em, width = (w/h)em
    const ratio = w / h;
    cssLines.push(`.icon-${name} { width: ${ratio.toFixed(3)}em; background-size: ${(W / h).toFixed(3)}em ${(H / h).toFixed(3)}em; background-position: -${(x / h).toFixed(3)}em -${(y / h).toFixed(3)}em; }`);
  });
});

fs.writeFileSync(OUT_CSS, cssLines.join('\n') + '\n');
fs.writeFileSync(OUT_JSON, JSON.stringify(manifest, null, 2));
console.log(`Generated ${totalNamed} icon classes -> ${OUT_CSS}`);
console.log(`Manifest -> ${OUT_JSON}`);
